def revert_metrics(c, settings):
    res = targets.evaluate(c, settings, quick=True)
    rows = res["rows"]
    gestures, holds = [], []
    for r in rows:
        g = [x["slip"] for x in r["stab"]] + [r["pb"]["slip"]]
        if r["car"].tier in ("C", "B", "A", "S"):
            gestures += g
        elif r["car"].tier == "E":
            gestures.append(r["pb"]["slip"])
        holds += [x["slip"] for x in r["hold"] + r["uturn"]]
    worst = lambda key: max(abs(r[key]) for r in rows)
    exit_err = max(abs(r["drift"]["exit"] / r["drift0"]["exit"] - 1) for r in rows)
    yaw_err = max(abs(r["drift"]["yaw"] / r["drift0"]["yaw"] - 1) for r in rows)
    hold_L = max(x["L"] for r in rows for x in r["hold"])
    fails = [key for key, _ in targets.TARGETS if res.get(key) is False]
    return dict(fails=fails, gesture=min(gestures), hold=max(holds), runon=max(r["runon"]["runon"] for r in rows),
                drift="%+.0f / %.0f / %.0f" % (100 * max((r["drift_err"] for r in rows), key=abs), 100 * yaw_err, 100 * exit_err),
                hold_L=hold_L)


def section_revert(c):
    """Each proposed attribute put back to its contract default, everything else as proposed."""
    rows = []
    cases = [("proposed (nothing reverted)", dict(PROPOSED))]
    for key in PROPOSED:
        a = dict(PROPOSED)
        a[key] = CONTRACT_DEFAULTS[key]
        cases.append(("`%s` back to %g" % (key, CONTRACT_DEFAULTS[key]), a))
    for label, a in cases:
        m = revert_metrics(c, Settings(a, RECOMMENDED_CODE))
        warn = a["SpinWarnLevel"]
        rows.append([label, ", ".join(m["fails"]) or "none", "%.0f" % m["gesture"], "%.0f" % m["hold"], "%.1f" % m["runon"], m["drift"],
                     "yes" if m["hold_L"] > warn else "no"])
    return table(["Change from the proposal", "CONTRACT 9 targets that fail", "smallest required gesture slip deg (75 = spin)",
                  "largest hold / U-turn slip deg", "largest run-on deg", "drift worst radius % / yaw % / exit %",
                  "holds light the spin warning"], rows)


