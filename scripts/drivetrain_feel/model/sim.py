    res_c, res_p = evaluate_many([{}, dict(PROPOSED)], pool=pool)
    out["summary"] = section_summary(c, res_p, res_c)
    out["validation"] = section_validation(c)
    out["profiles"] = section_profiles(c, cars + [SERAPH_SPAWNED])
    out["straight"], out["shifts"] = section_straight(c, cars)
    out["longitudinal"] = section_longitudinal(c, cars)
    out["runon"], out["corner"] = section_chassis(c, cars + [SERAPH_SPAWNED])
    out["drift"] = section_drift(c, cars + [SERAPH_SPAWNED])
    out["churn"] = section_churn(c, cars + [SERAPH_SPAWNED])
    out["spin_contract_not"], out["spin_contract_must"] = section_spin(c, cars + [SERAPH_SPAWNED], contract())
    out["spin_proposed_not"], out["spin_proposed_must"] = section_spin(c, cars + [SERAPH_SPAWNED], proposed())
    out["targets"] = section_targets({"contract section 4 + spec B defaults": res_c, "proposed": res_p})
