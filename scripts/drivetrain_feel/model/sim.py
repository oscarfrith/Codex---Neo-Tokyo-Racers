def section_validation(c):
    lines = []
    rows = []
    for hz in (60, 120):
        dt = 1 / hz
        v = Vehicle(c, SERAPH_SPAWNED, None, balance_on=False)
        t, i, worst, cells = 0.0, 0, 0.0, []
        W = Inputs.keys(w=True)
        while i < len(SERAPH_RUN_BALANCE_OFF):
            v.step(W, dt)
            t += dt
            if t >= SERAPH_RUN_BALANCE_OFF[i][0] - 1e-9:
                measured = SERAPH_RUN_BALANCE_OFF[i][1]
                worst = max(worst, abs(v.forward_mph - measured))
                if SERAPH_RUN_BALANCE_OFF[i][0] in (0.5, 1.05, 1.8, 2.6, 3.6, 4.4, 5.7):
                    cells.append("%.2f s %d/%.0f" % (SERAPH_RUN_BALANCE_OFF[i][0], measured, v.forward_mph))
                i += 1
        rows.append(["balance off, %d Hz" % hz, ", ".join(cells), "%.1f mph" % worst])
    lines.append(table(["Seraph as spawned (PI 946)", "measured / model, mph", "largest difference"], rows))
    v = Vehicle(c, SERAPH_SPAWNED, None)
    t, t100, at44 = 0.0, None, None
    while t < 6:
        v.step(Inputs.keys(w=True), DT)
        t += DT
        if t100 is None and v.forward_mph >= 100: t100 = t
        if at44 is None and t >= 4.4 - 1e-9: at44 = v.forward_mph
    b = Vehicle(c, SERAPH_SPAWNED, None)
    b.set_speed(131)
    tb = 0.0
    while b.forward_mph > 1.5 and tb < 10:
        b.step(Inputs.keys(s=True), DT)
        tb += DT
    k = Vehicle(c, SERAPH_SPAWNED, None)
    k.set_speed(SERAPH_COAST["start"])
    for _ in range(int(round(SERAPH_COAST["seconds"] / DT))):
        k.step(Inputs(), DT)
    lines.append("")
    lines.append(table(["Seraph as spawned, balance on (PI 946)", "measured in Play (v3, 2026-10-06)", "today's model"], [
        ["0-100 mph", "%.2f s" % SERAPH_BALANCE_ON["t100"], "%.2f s" % t100],
        ["speed at 4.4 s", "%d mph" % SERAPH_BALANCE_ON["mph_at_4_4"], "%.0f mph" % at44],
        ["brake 131-0", "%.1f s" % SERAPH_BALANCE_ON["brake_131_to_0"], "%.2f s" % tb],
        ["coast 34 mph for 1.6 s", "%d mph" % SERAPH_COAST["measured_end"], "%.1f mph (known gap, critique 20)" % k.forward_mph],
    ]))
    return "\n".join(lines)


