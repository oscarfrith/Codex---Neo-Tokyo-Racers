GENERATED = ("validation", "profiles", "straight", "shifts", "longitudinal", "runon", "corner", "drift", "churn", "spin_contract",
             "spin_proposed", "targets", "framerate", "dials", "literal", "proposal", "revert", "physics", "seraph")


def build(c):
    cars = stock_cars()
    out = {}
    out["validation"] = section_validation(c)
    out["profiles"] = section_profiles(c, cars + [SERAPH_SPAWNED])
    out["straight"], out["shifts"] = section_straight(c, cars)
    out["longitudinal"] = section_longitudinal(c, cars)
    out["runon"], out["corner"] = section_chassis(c, cars)
    out["drift"] = section_drift(c, cars)
    out["churn"] = section_churn(c, cars)
    out["spin_contract"] = section_spin(c, cars, contract())
    out["spin_proposed"] = section_spin(c, cars, proposed())
    out["targets"], _ = section_targets(c)
    out["framerate"] = section_framerate(c, [cars[0], cars[2], cars[5]])
    out["dials"] = section_dials(c)
    out["literal"] = section_literal(c)
    out["proposal"] = section_proposal()
    out["revert"] = section_revert(c)
    out["physics"] = section_physics(c)
    sp = section_straight(c, [SERAPH_SPAWNED])[0]
    out["seraph"] = sp + "\n\n" + section_spin(c, [SERAPH_SPAWNED], proposed())
    return out


def write_results(sections):
    path = os.path.join(HERE, "RESULTS.md")
    text = io.open(path, encoding="utf-8").read()
    for name, body in sections.items():
        pattern = re.compile(r"(<!-- BEGIN:%s -->\n).*?(<!-- END:%s -->)" % (name, name), re.S)
        if not pattern.search(text):
            raise SystemExit("RESULTS.md has no marker for section %s" % name)
        text = pattern.sub(lambda m: m.group(1) + body + "\n" + m.group(2), text)
    io.open(path, "w", encoding="utf-8", newline="\n").write(text)


def main():
    start = time.time()
    c = Config()
    sections = build(c)
    for name in GENERATED:
        print("\n## " + name + "\n")
        print(sections[name])
    print("\n(%.0f s)" % (time.time() - start))
    if "--write" in sys.argv:
        write_results(sections)
        print("RESULTS.md generated sections refreshed")


if __name__ == "__main__":
    main()
