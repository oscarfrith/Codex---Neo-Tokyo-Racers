def _eval_job(args):
    a, ci, rates, quick = args
    res = targets.evaluate(_C, Settings(a), cars=[targets.all_cars()[ci]], rates=rates, quick=quick)
    return res["rows"][0]


def evaluate_many(configs, rates=targets.RATES, quick=False, pool=None):
    """targets.evaluate for several attribute dicts, one process per (config, car). Falls back to one process if the pool
    breaks or stalls (a Windows worker that dies would otherwise hang the map)."""
    n = len(targets.all_cars())
    jobs = [(a, ci, rates, quick) for a in configs for ci in range(n)]
    global _POOL_OK
    rows = None
    if pool is not None and _POOL_OK:
        try:
            rows = list(pool.map(_eval_job, jobs, timeout=60 + 30 * len(configs)))
        except (cf.BrokenExecutor, cf.TimeoutError, OSError) as error:
            _POOL_OK = False
            print("process pool failed (%s); evaluating in one process" % type(error).__name__, flush=True)
    if rows is None:
        if _C is None:
            _init()
        rows = [_eval_job(j) for j in jobs]
    out = []
    for i in range(len(configs)):
        res = targets.judge(rows[i * n:(i + 1) * n], (60,) if quick else rates)
        res["margins"] = targets.margins(res)
        out.append(res)
    return out


def worst_values(res):
    w = dict(runon=0.0, runon_body=0.0, drift=0.0, driftpre=0.0, taprpm=0.0, tap=0, top=0.0, boost=0.0)
    for r in res["rows"]:
        w["top"] = max(w["top"], abs(r.get("top_err", 0)))
        if "boost" in r:
            w["boost"] = max(w["boost"], abs(r["boost"]["endless"] / r["boost0"]["endless"] - 1))
        for hz, h in r["hz"].items():
            if "runon" not in h:
                continue
            w["runon"] = max(w["runon"], h["runon"]["runon"])
            w["runon_body"] = max(w["runon_body"], h["runon"]["runon_body"])
            for k in ("drift", "driftpre"):
                if abs(h[k + "_err"]) > abs(w[k]):
                    w[k] = h[k + "_err"]
            w["taprpm"] = max(w["taprpm"], h["tap"]["rpm"] or 0)
            w["tap"] = max(w["tap"], h["tap"]["shifts"])
    return w


def target_value(res, key):
    """The worst number behind each target, for the targets table."""
    w = worst_values(res)
    m = res["margins"]
    S = next((r for r in res["rows"] if r["car"].tier == "S" and "spawned" not in r["car"].name), None)
    if key == "top":
        return "worst %.1f%%" % (100 * w["top"])
    if key == "s0100":
        return "%s s" % f2(S["straight"]["t100"])
    if key == "s090":
        return "%s s" % f1(S["straight"]["t90"])
    if key == "runon":
        return "worst %.1f deg (body %.1f)" % (w["runon"], w["runon_body"])
    if key == "tap":
        return "worst %d" % w["tap"]
    if key == "taprpm":
        return "worst %.2f" % w["taprpm"]
    if key in ("drift", "driftpre"):
        return "worst %+.0f%%" % (100 * w[key])
    if key in ("hold", "uturn", "nospin"):
        keys = [k for k, _, _ in sc.MUST_NOT if targets._nospin_group(k) == key]
        worst = max(r["hz"][hz]["spin"][k]["slip"] for r in res["rows"] for hz in r["hz"] for k in keys)
        return "max %.0f deg" % worst
    if key == "gesture":
        vals = [r["hz"][hz]["spin"][k]["slip"] for r in res["rows"] if r["car"].tier in targets.GESTURE_TIERS
                for hz in r["hz"] for k, _, _ in sc.MUST_SPIN]
        return "min %.0f deg" % min(vals)
    if key == "pbE":
        vals = [r["hz"][hz]["spin"]["pb"]["slip"] for r in res["rows"] if r["car"].tier == "E" for hz in r["hz"]]
        return "min %.0f deg" % min(vals)
    if key == "boost":
        return "worst %.1f%%" % (100 * w["boost"])
    return ""


