def _mark(x, must):
    s = "%.0f" % x["slip"]
    if x["slip"] > sc.SPIN_SLIP:
        return ("**%s**" % s) if must else ("**%s SPIN**" % s)
    return s if not must else s + " (no spin)"


def section_spin(c, cars, settings, dt=DT):
    rows_n, rows_m = [], []
    for car in cars:
        cache = {k: f(c, car, settings, dt) for k, _, f in sc.MUST_NOT + sc.MUST_SPIN}
        rows_n.append([short(car)] + [" / ".join(_mark(cache[k], False) for k in keys) for _, keys in GROUPS_NOT]
                      + ["yes" if any(cache[k]["warn"] for k, _, _ in sc.MUST_NOT) else "no"])
        k = sc.catch(c, car, settings, dt)
        rows_m.append([short(car)] + [" / ".join(_mark(cache[kk], True) for kk in keys) for _, keys in GROUPS_MUST]
                      + ["L %.2f" % max(cache[kk]["L"] for kk in ("stab0", "stab10", "stab20", "pb")),
                         "%.2f rad/s, L %.2f" % (k["r_after_0_3"] or 0, k["L_after"])])
    return (table(["Car (max slip deg; 75 = spin)"] + [g for g, _ in GROUPS_NOT] + ["any must-not case lights the spin warning"], rows_n),
            table(["Car (max slip deg; must pass 75)"] + [g for g, _ in GROUPS_MUST] + ["peak L", "catch: yaw rate 0.3 s after a lift"], rows_m))


def section_targets(results):
    names = list(results)
    rows = []
    for key, text in targets.TARGETS:
        cells = [text]
        for n in names:
            res = results[n]
            value = res.get(key)
            mark = "-" if value is None else ("PASS" if value else "**FAIL**")
            cells.append("%s (%s)" % (mark, target_value(res, key)) if value is not None else "-")
        rows.append(cells)
    return table(["Target (six stock cars + as-spawned Seraph; 60 Hz, and %s Hz for run-on, tap, drift and spin)" % " / ".join(str(r) for r in targets.RATES)] + names, rows)


