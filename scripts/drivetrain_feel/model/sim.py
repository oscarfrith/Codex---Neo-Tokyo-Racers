def f2(x):
    return "-" if x is None else "%.2f" % x


def f1(x):
    return "-" if x is None else "%.1f" % x


def f0(x):
    return "-" if x is None else "%.0f" % x


def pct(a, b):
    return "%+.0f%%" % (100 * (a / b - 1)) if b else "-"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def short(car):
    return "%s %s%s" % (car.tier, car.name.split(" ")[0], " (spawned)" if "spawned" in car.name else "")


